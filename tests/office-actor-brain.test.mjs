import assert from "node:assert/strict";
import { ACTOR_STATES, createActorBrain, setActorRisk, transitionActor, tickActor, isWalkable, moveWithCollision } from "../src/office-actor-brain.js";
assert.deepEqual(Object.keys(ACTOR_STATES), ["idle","working","exploring","talking","resting","worried"]);
const brain=createActorBrain({id:"worker-1",home:{x:0,z:0},seed:7});
assert.equal(brain.state,"idle");
transitionActor(brain,"working");
assert.ok(brain.duration>=5 && brain.duration<=12);
const event=tickActor(brain,0.25);
assert.equal(event,null);
setActorRisk(brain,80);
assert.equal(brain.state,"worried");
assert.equal(brain.lastEvent,"Sinal de atenção: revisar condições de trabalho");
setActorRisk(brain,20);
brain.elapsed=brain.duration;
tickActor(brain,0.1);
assert.notEqual(brain.state,"worried");
const bounds={minX:-5,maxX:5,minZ:-5,maxZ:5};
const obstacles=[{minX:0.5,maxX:1.5,minZ:-1,maxZ:1}];
assert.equal(isWalkable({x:0,z:0},bounds,obstacles),true);
assert.equal(isWalkable({x:1,z:0},bounds,obstacles),false);
assert.deepEqual(moveWithCollision({x:0,z:0},{x:2,z:0},bounds,obstacles,2,1),{x:0,z:0});
assert.ok(isWalkable(moveWithCollision({x:0,z:0},{x:2,z:2},bounds,obstacles,2,1),bounds,obstacles));
const exploring=createActorBrain({id:"worker-2",home:{x:0,z:0},seed:2});
transitionActor(exploring,"exploring",[{x:1,z:1},{x:2,z:1}]);
exploring.elapsed=exploring.duration;
const waypoint=tickActor(exploring,0.1);
assert.equal(waypoint.type,"waypoint");
assert.deepEqual(waypoint.target,{x:2,z:1});
console.log("office actor brain: ok");
